"""Which device this is, who made it, and how long it is supported.

Three separate rules want this, and all three want it in a place a person can
actually reach rather than buried in a spec sheet:

- **GPSR** (EU 2023/988, since Dec 2024) wants the model, a batch or serial,
  and the manufacturer's name and postal address *on the product or its
  packaging*. A 10cm cube has room for a label; the device shows the same
  thing on its own page so a user can read it without turning the thing over.
- **The RED cybersecurity delegated act** (2022/30/EU, mandatory since Aug
  2025) wants a device identifiable and a way to report a problem with it.
- **The Cyber Resilience Act** (EU 2024/2847) wants a declared support
  period, during which security updates are provided, and a contact that
  reaches someone.

`SUPPORT_UNTIL` is a promise, not a label. It is the date until which
security updates will be published, and the update machinery in `updates/`
is what keeps it. Move it when that stops being true, and say so.

**Before anything is sold, `MANUFACTURER` and `ADDRESS` have to be the
registered ones.** They are placeholders here; a device shipped with these is
not compliant and, more to the point, gives a buyer nobody to complain to.
"""

import os

MODEL = "Trstenko"
MODEL_ID = "TRS-1"
HARDWARE_REVISION = "A"

# TODO before sale: the registered company name and address. GPSR requires
# both on the product; these are placeholders and are deliberately obvious.
MANUFACTURER = "Trstenko (Moje podjetje student company)"
ADDRESS = "— address required before sale —"
COUNTRY = "Slovenia"

# CRA: the period security updates are provided for, counted from first
# sale. Five years is the shortest span that is defensible for a device
# somebody keeps on a desk.
SUPPORT_UNTIL = "2031-09-01"

# Somewhere a vulnerability report lands. CRA and EN 18031 both want one, and
# a repository with no contact gets its problems posted publicly instead.
SECURITY_CONTACT = "https://github.com/majcek210/trstenko/security/advisories"

# The device talks, so the AI Act's transparency rule (Art. 50, from Aug
# 2026) applies: a person has to be able to tell they are talking to software.
# The face helps, but the page says it in words.
AI_NOTICE = ("Trstenko is a computer program. What it says is generated by a "
             "language model and can be wrong.")


def serial(data_root=None):
    """A stable identifier for this unit.

    The Pi's own CPU serial where there is one, because it survives
    reflashing the card and is what a support conversation can refer to.
    Anywhere else, a random id kept next to the settings -- the emulator and
    a dev machine both need to be identifiable without pretending to be a
    board they are not.
    """
    found = _cpu_serial()
    if found:
        return "%s-%s" % (MODEL_ID, found[-8:].upper())
    return "%s-%s" % (MODEL_ID, _local_id(data_root))


def _cpu_serial():
    try:
        with open("/proc/cpuinfo", "r", encoding="utf-8") as fh:
            for line in fh:
                if line.lower().startswith("serial"):
                    value = line.split(":", 1)[1].strip()
                    if value and set(value) != {"0"}:
                        return value
    except OSError:
        pass
    return ""


def _local_id(data_root):
    import uuid

    from .updates.config import DEFAULT_DATA_ROOT

    root = data_root or DEFAULT_DATA_ROOT
    path = os.path.join(root, "device-id")
    try:
        with open(path, "r", encoding="utf-8") as fh:
            found = fh.read().strip()
        if found:
            return found
    except OSError:
        pass

    found = uuid.uuid4().hex[:8].upper()
    try:
        os.makedirs(root, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(found)
    except OSError:
        pass  # a read-only root still gets an id, just a new one each boot
    return found


def identity(data_root=None):
    """What the page shows and what a label has to carry."""
    from .updates import version as version_mod

    return {
        "model": MODEL,
        "model_id": MODEL_ID,
        "hardware_revision": HARDWARE_REVISION,
        "serial": serial(data_root),
        "firmware": str(version_mod.current()),
        "manufacturer": MANUFACTURER,
        "address": ADDRESS,
        "country": COUNTRY,
        "support_until": SUPPORT_UNTIL,
        "security_contact": SECURITY_CONTACT,
        "ai_notice": AI_NOTICE,
    }
